function mk(id: string, name: string, ring: number[][]): StateFeature {
  return {
    type: "Feature",
    properties: { id, name, state: name },
    geometry: {
      type: "Polygon",
      coordinates: [[...ring, ring[0]],
      ],
    },
  };
}

